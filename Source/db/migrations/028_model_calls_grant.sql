-- 028_model_calls_grant.sql
-- Прикладная роль должна уметь писать в журнал обращений к моделям.
--
-- Таблица ai.model_calls создавалась под ETL, который работал под владельцем
-- базы, поэтому прав у ishmed_app на неё не было. Теперь в модели ходят бот и
-- веб, а знать стоимость разговора к концу пилота нужно по факту, а не по
-- прикидке: интервью с озвучкой и расшифровкой — самая дорогая операция в
-- продукте.
--
-- Только INSERT: читать и править журнал приложению незачем.

GRANT INSERT ON ai.model_calls TO ishmed_app;
GRANT USAGE, SELECT ON SEQUENCE ai.model_calls_id_seq TO ishmed_app;

COMMENT ON TABLE ai.model_calls IS
  'Журнал обращений к моделям: задержка и токены по каждому вызову. '
  'Пишет приложение, читает владелец при разборе стоимости.';
