const TABLES: Record<Locale, Record<Key, string>> = { ru: RU, uz: UZ }

export type Vars = Record<string, string | number>

function format(text: string, vars?: Vars): string {
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  )
}

type Ctx = {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (key: Key, vars?: Vars) => string
}

const I18nContext = createContext<Ctx | null>(null)

function initialLocale(): Locale {
  const saved = localStorage.getItem(STORAGE_KEY)
  return saved === 'uz' || saved === 'ru' ? saved : 'ru'
}

export function I18nProvider({ children, initial }: { children: ReactNode; initial?: string }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale)

  // Язык пользователя приходит с /api/auth/me уже после первого рендера.
  // Применяем его, только если человек не переключал язык руками в этой
  // вкладке: иначе ответ сервера отменял бы только что сделанный выбор.
  useEffect(() => {
    if (!initial || localStorage.getItem(STORAGE_KEY)) return
    if (initial === 'uz' || initial === 'ru') setLocaleState(initial)
  }, [initial])

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  // `api.ts` разбирает ошибки сервера вне React и хук вызвать не может,
  // поэтому отдаём ему функцию перевода при каждой смене языка.
  useEffect(() => {
    setApiTranslator((key, vars) => format(TABLES[locale][key as Key] ?? key, vars))
  }, [locale])

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next)
    localStorage.setItem(STORAGE_KEY, next)
    // Сохранение на сервере не блокирует переключение: интерфейс обязан
    // переключиться сразу, а не после round-trip. Не сохранилось — язык
    // всё равно останется в localStorage этого браузера.
    api.post('/api/auth/locale', { locale: next }).catch(() => {})
  }, [])

  const value = useMemo<Ctx>(
    () => ({
      locale,
      setLocale,
      t: (key, vars) => format(TABLES[locale][key] ?? RU[key], vars),
    }),
    [locale, setLocale],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n вызван вне I18nProvider')
  return ctx
}

/** Короткая форма для компонентов, которым нужен только перевод. */
export function useT(): (key: Key, vars?: Vars) => string {
  return useI18n().t
}

/** Локаль для Intl: узбекская латиница — uz-Latn-UZ. */
export function intlLocale(locale: Locale): string {
  return locale === 'uz' ? 'uz-Latn-UZ' : 'ru-RU'
}
